const unsigned char *vg_font8x8(int ch)
{
    if (ch < 32 || ch > 127) ch = 32;
    return kFont[ch - 32];
}

/* Turbo C's charsize scales the 8x8 cell; the stroked fonts are wider,
 * so a nominal multiplier of 1 keeps DEFAULT_FONT metrics exact. */
static void size_factors(int *mx, int *my)
{
    if (vg.text.charsize == USER_CHAR_SIZE) {
        *mx = vg.usr_multx > 0 && vg.usr_divx > 0 ? vg.usr_multx / vg.usr_divx : 1;
        *my = vg.usr_multy > 0 && vg.usr_divy > 0 ? vg.usr_multy / vg.usr_divy : 1;
        if (*mx < 1) *mx = 1;
        if (*my < 1) *my = 1;
    } else {
        int s = vg.text.charsize;
        if (s < 1)  s = 1;
        if (s > 10) s = 10;
        /* The stroked fonts run larger than the bitmap one at the same size. */
        if (vg.text.font != DEFAULT_FONT) s = s * 4 / 3 + (s > 1 ? 1 : 0);
        *mx = *my = s;
    }
}

int textheight(const char *s)
{
    int mx, my;
    (void)s;
    size_factors(&mx, &my);
    return 8 * my;
}

int textwidth(const char *s)
{
    int mx, my;
    size_factors(&mx, &my);
    return (int)(s ? strlen(s) : 0) * 8 * mx;
}

static void draw_glyph(int ox, int oy, int ch, int mx, int my, int vertical)
{
    const unsigned char *g = vg_font8x8(ch);
    int row, col, i, j;
    for (row = 0; row < 8; row++) {
        for (col = 0; col < 8; col++) {
            if (!((g[row] >> (7 - col)) & 1)) continue;
            for (j = 0; j < my; j++) {
                for (i = 0; i < mx; i++) {
                    if (vertical)
                        /* Rotated 90 degrees anticlockwise, as VERT_DIR is. */
                        vg_plot(ox + row * my + j, oy - col * mx - i, vg.color);
                    else
                        vg_plot(ox + col * mx + i, oy + row * my + j, vg.color);
                }
            }
        }
    }
}

static void render(int x, int y, const char *s)
{
    int mx, my, w, h, i, len;
    int vertical = (vg.text.direction == VERT_DIR);

    if (!s) return;
    vg_ensure_init();
    size_factors(&mx, &my);
    len = (int)strlen(s);
    w   = len * 8 * mx;
    h   = 8 * my;

    if (vertical) {
        /* The string runs upward from (x, y). Justification is relative to
         * the text direction, so horiz applies along the run and vert
         * across it. */
        int total = len * 8 * mx;
        if (vg.text.horiz == CENTER_TEXT)     y += total / 2;
        else if (vg.text.horiz == RIGHT_TEXT) y += total;
        if (vg.text.vert == CENTER_TEXT)      x -= (8 * my) / 2;
        else if (vg.text.vert == BOTTOM_TEXT) x -= 8 * my;
        for (i = 0; i < len; i++)
            draw_glyph(x, y - i * 8 * mx, (unsigned char)s[i], mx, my, 1);
    } else {
        if (vg.text.horiz == CENTER_TEXT) x -= w / 2;
        else if (vg.text.horiz == RIGHT_TEXT) x -= w;
        /* BOTTOM_TEXT means the given y is the baseline, so shift up. */
        if (vg.text.vert == BOTTOM_TEXT) y -= h;
        else if (vg.text.vert == CENTER_TEXT) y -= h / 2;
        for (i = 0; i < len; i++)
            draw_glyph(x + i * 8 * mx, y, (unsigned char)s[i], mx, my, 0);
    }
    vg_tick();
}

void outtextxy(int x, int y, const char *s) { render(x, y, s); }

void outtext(const char *s)
{
    int mx, my;
    render(vg.cpx, vg.cpy, s);
    size_factors(&mx, &my);
    /* outtext advances the current position, outtextxy does not. */
    if (vg.text.direction == HORIZ_DIR)
        vg.cpx += (int)(s ? strlen(s) : 0) * 8 * mx;
    else
        vg.cpy -= (int)(s ? strlen(s) : 0) * 8 * mx;
}

void settextstyle(int font, int direction, int charsize)
{
    if (font < 0 || font > BOLD_FONT) { vg.result = grInvalidFontNum; return; }
    vg.text.font      = font;
    vg.text.direction = direction ? VERT_DIR : HORIZ_DIR;
    vg.text.charsize  = charsize;
}

void settextjustify(int horiz, int vert)
{
    vg.text.horiz = horiz;
    vg.text.vert  = vert;
}

void setusercharsize(int multx, int divx, int multy, int divy)
{
    vg.usr_multx = multx; vg.usr_divx = divx;
    vg.usr_multy = multy; vg.usr_divy = divy;
    vg.text.charsize = USER_CHAR_SIZE;
}

void gettextsettings(struct textsettingstype *t) { if (t) *t = vg.text; }
